"""Bounded, isolated local demo sessions for the engine's manual discard rule.

Imported only by the viewer's discard POST routes, keeping board previews stdlib
only. Sample hands are fixtures, not generated by unfinished game play.
"""

from collections import OrderedDict
from secrets import token_urlsafe
from threading import Lock

from catan.actions import DiscardAction
from catan.engine import apply_action, resolve_seven
from catan.state import GameState, Phase, _integer, new_game


SAMPLE_HANDS = ((4, 3, 2, 1, 0), (1, 2, 0, 3, 1), (0, 1, 3, 0, 5), (2, 2, 2, 2, 0))


def snapshot(session: str, state: GameState, revision: int) -> dict:
    return {
        "session": session,
        "revision": revision,
        "phase": state.phase.name,
        "current_player": state.current_player,
        "discard_player": state.discard_player,
        "discard_pending": state.discard_pending.tolist(),
        "hands": state.hands.tolist(),
        "bank": state.bank.tolist(),
        "last_roll": state.last_roll,
    }


class DiscardDemo:
    """Keep at most 32 sessions; apply one versioned choice at a time per server.

    The short lock protects revision checks and functional replacement, preventing
    duplicate/concurrent submissions from discarding twice. No file persistence.
    """

    def __init__(self, capacity: int = 32) -> None:
        self.capacity = capacity
        self.sessions: OrderedDict[str, tuple[GameState, int]] = OrderedDict()
        self.lock = Lock()

    def handle(self, route: str, payload: dict) -> tuple[int, dict]:
        if not isinstance(payload, dict):
            return 400, {"error": "Send a JSON object."}
        with self.lock:
            try:
                if route == "/api/discard/new":
                    seed = _integer(payload.get("seed", 0), "seed")
                    if not 0 <= seed <= 2**32 - 1:
                        raise ValueError("seed must be from 0 to 4294967295")
                    state = new_game(seed, payload.get("n_players", 4))
                    state.current_player = _integer(
                        payload.get("current_player", 0), "current_player"
                    )
                    state.phase = Phase.ROLL
                    state.setup_index = len(state.setup_order)
                    state.hands[:] = SAMPLE_HANDS[: state.n_players]
                    state.bank[:] -= state.hands.sum(axis=0)
                    state.validate()
                    session = token_urlsafe(18)
                    self.sessions[session] = (state, 0)
                    if len(self.sessions) > self.capacity:
                        self.sessions.popitem(last=False)
                    return 200, snapshot(session, state, 0)
                session = payload.get("session")
                if not isinstance(session, str) or session not in self.sessions:
                    return 404, {
                        "error": "Demo session expired. Load sample hands again."
                    }
                state, revision = self.sessions[session]
                if _integer(payload.get("revision"), "revision") != revision:
                    return 409, {
                        "error": "This choice is outdated. Review the current hand.",
                        "current": snapshot(session, state, revision),
                    }
                if route == "/api/discard/seven":
                    following = resolve_seven(state)
                elif route == "/api/discard/choose":
                    following = apply_action(
                        state,
                        DiscardAction(payload.get("player"), payload.get("resources")),
                    )
                else:
                    return 404, {"error": "Unknown discard route."}
                self.sessions[session] = (following, revision + 1)
                self.sessions.move_to_end(session)
                return 200, snapshot(session, following, revision + 1)
            except (ValueError, TypeError) as error:
                return 400, {"error": str(error)}


DEMO = DiscardDemo()
